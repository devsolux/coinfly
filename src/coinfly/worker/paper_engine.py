# SYNTHETIC paper settlement schedule (never venue evidence): funding intervals
# per declared subtype and the declared rate per interval (long pays when
# positive). Visible in every event record and in the balance snapshot.
PAPER_FUNDING_INTERVALS: dict[ProductSubtype, timedelta] = {
    ProductSubtype.PERPETUAL_NO_EXPIRY: timedelta(hours=8),
    ProductSubtype.PERPETUAL_STYLE_FUTURE: timedelta(hours=1),
}
PAPER_FUNDING_RATE_PER_INTERVAL = Decimal("0.0001")


def _interval_start(now: datetime, interval: timedelta) -> datetime:
    epoch = datetime(1970, 1, 1, tzinfo=timezone.utc)
    elapsed = int((now.astimezone(timezone.utc) - epoch).total_seconds())
    seconds = int(interval.total_seconds())
    return epoch + timedelta(seconds=elapsed - elapsed % seconds)


def paper_instruments(track: ProductTrack, quote: str) -> tuple[PaperInstrument, ...]:
    return tuple(PaperInstrument(instrument_id=f"{base}-{quote}", base_currency=base,
                                 quote_currency=quote, product_track=track,
                                 minimum_notional=Decimal("1"))
                 for base in ("BTC", "ETH", "SOL"))


class LocalPaperEngine:
    def __init__(
        self, config: EngineConfig, context: ContextKey, writer: Writer, reducer: FactReducer,
        interlock: ContextInterlock, *, ready: Callable[[], None],
        on_change: Callable[[], None] | None = None,
    ) -> None:
        if context.environment != Environment.SANDBOX or config.environment != Environment.SANDBOX:
            raise DomainError("PAPER_REQUIRES_SANDBOX")
        if len(config.execution_scope) != 1:
            raise DomainError("PAPER_SINGLE_BOOK_REQUIRED")
        self.config, self.context = config, context
        self.writer, self.reducer, self.interlock = writer, reducer, interlock
        self._settled_events: set[str] = set()
        self._settlement_cursor: datetime | None = None
        self._ready, self._on_change = ready, on_change
        self._lock = threading.RLock()
        self._drain_lock = threading.Lock()
        self._matcher: PaperMatcher | None = None
        self._armed = False
        self._retired = False
        self._quiesced = False
        self._enabled_slots: set[str] = set()
        self._depth: dict[str, tuple[tuple[DepthLevel, ...], tuple[DepthLevel, ...], datetime]] = {}
        self._drain_used: dict[str, tuple[datetime, Decimal]] = {}
        self._default_instruments = paper_instruments(context.product_track, config.reporting_currency)
        self.scope = config.execution_scope[0]
        # Paper derivatives are admitted against the explicit synthetic linear
        # margin model of the local book; it is bound to the paper broker profile
        # and can never stand in for a live venue's margin.
        margin_model = PaperLinearMarginModel(profile_id=context.broker_profile_id) \
            if context.product_track == ProductTrack.PERPETUAL else None
        self.admission = AdmissionActor(writer, interlock, margin_model=margin_model, on_change=on_change)
        self.writer.call(self._schema)

    @staticmethod
    def _schema(connection: sqlite3.Connection) -> None:
        ensure_intent_causes_schema(connection)
        connection.execute(
            "CREATE TABLE IF NOT EXISTS wp_paper_books (authority_id TEXT NOT NULL, "
            "environment TEXT NOT NULL CHECK(environment='SANDBOX'), scope_id TEXT NOT NULL, "
            "product_track TEXT NOT NULL, context_json TEXT NOT NULL, state_json TEXT NOT NULL, "
            "PRIMARY KEY(authority_id,environment,scope_id,product_track))")
        connection.execute(
            "CREATE TABLE IF NOT EXISTS wp_paper_archives (context_id TEXT PRIMARY KEY, "
            "scope_id TEXT NOT NULL, context_json TEXT NOT NULL, target_context_json TEXT NOT NULL, "
            "state_json TEXT NOT NULL, state_sha256 TEXT NOT NULL, fact_sequence INTEGER NOT NULL, "
            "retirement_proof_id TEXT NOT NULL)")
        connection.execute("CREATE TRIGGER IF NOT EXISTS wp_paper_archives_no_update "
            "BEFORE UPDATE ON wp_paper_archives BEGIN SELECT RAISE(ABORT,'immutable paper archive'); END")
        connection.execute("CREATE TRIGGER IF NOT EXISTS wp_paper_archives_no_delete "
            "BEFORE DELETE ON wp_paper_archives BEGIN SELECT RAISE(ABORT,'immutable paper archive'); END")

    @property
    def matcher(self) -> PaperMatcher:
        if self._matcher is None:
            raise DomainError("PAPER_NOT_INITIALIZED")
        return self._matcher

    @property
    def _instruments(self) -> tuple[PaperInstrument, ...]:
        """The book's instrument universe: persisted definitions plus additions."""
        if self._matcher is not None:
            return self._matcher.instruments
        return self._default_instruments

    def instrument_ids(self) -> tuple[str, ...]:
        return tuple(item.instrument_id for item in self._instruments)

    def ensure_instruments(self, instruments: tuple[PaperInstrument, ...]) -> tuple[str, ...]:
        """Add discovered instruments to the persisted book; idempotent, never removes."""
        with self.interlock.lock, self._lock:
            if self._retired:
                raise DomainError("PAPER_CONTEXT_RETIRED")
            previous = self.matcher.dump_state()
            added: list[str] = []
            try:
                for instrument in instruments:
                    if self.matcher.add_instrument(instrument):
                        added.append(instrument.instrument_id)
                if added:
                    self.writer.call(self._persist_tx)
            except BaseException:
                self._matcher = PaperMatcher.restore(self.context, (), previous)
                raise
        if added:
            self._notify()
        return tuple(added)

    def initialize(self, config: EngineConfig, context: ContextKey) -> None:
        self._ready()
        if config != self.config or context != self.context or self._matcher is not None:
            raise DomainError("PAPER_CONTEXT_MISMATCH")
        row = self.writer.call(lambda connection: connection.execute(
            "SELECT context_json,state_json FROM wp_paper_books "
            "WHERE authority_id=? AND environment='SANDBOX' AND scope_id=? AND product_track=?",
            (context.authority_id, self.scope, context.product_track.value)).fetchone())
        # Explicit, configured synthetic funding: applied once per NEW paper book
        # (the SIMULATION_SEED event below), never on restart, never live capital.
        initial = config.paper_funding.amount
        balances = {config.reporting_currency: initial}
        margin: PaperMarginBook | None = None
        if row is not None:
            source = ContextKey.model_validate_json(row[0])
            restored = PaperMatcher.restore(source, self._instruments, json.loads(row[1]))
            if source == context:
                self._matcher = restored
                return
            self.writer.call(lambda connection: assert_context_closed_tx(connection, source))
            if restored.open_orders or (restored.margin is not None and restored.margin.positions):
                raise DomainError("PAPER_PREVIOUS_BOOK_NOT_FLAT")
            if any(value != 0 for currency, value in restored.balances.items()
                   if currency != config.reporting_currency):
                raise DomainError("PAPER_PREVIOUS_BOOK_NOT_FLAT")
            self._matcher = restored.rebind_flat(context)
            self.writer.call(self._persist_tx)
            return
        elif context.product_track == ProductTrack.PERPETUAL:
            margin = PaperMarginBook(initial)
        if context.product_track == ProductTrack.PERPETUAL:
            balances = {}
        candidate = PaperMatcher(context, self._instruments, initial_balances=balances, margin=margin)
        self._matcher = candidate
        try:
            def save(connection: sqlite3.Connection) -> None:
                if row is None:
                    post_tx(connection, JournalFrame(context=context, scope_id=self.scope,
                        event_kind="SIMULATION_SEED", evidence_id=f"seed-{context.product_track.value}",
                        entries=(JournalEntry(account="assets:cash", asset=config.reporting_currency, amount=initial),
                                 JournalEntry(account="equity:simulation_seed", asset=config.reporting_currency, amount=-initial))))
                    self.admission.drawdown.record_tx(connection, context, self.scope, equity=initial,
                        evidence_id=f"simulation-seed-{context.product_track.value}",
                        observed_at=datetime.now(timezone.utc), currency=config.reporting_currency)
                self._persist_tx(connection)
            self.writer.call(save)
        except BaseException:
            self._matcher = None
            raise

    def recover_existing(self) -> None:
        """Reopen exact committed venue truth without assets, reseeding or arming."""
        with self.interlock.lock, self._lock:
            state_json, retired_source = self.writer.call(self._recovery_state_tx)
            self._matcher = PaperMatcher.restore(self.context, self._instruments, json.loads(state_json))
            if retired_source:
                # This source exists only to re-attest a previously committed
                # retirement. An unpublished target may already own the mutable
                # book; explicit operation.retry alone resumes initialization.
                self._armed = False
                self._quiesced = True
                self._retired = True
                return
            orders = {order.client_order_id: order for order in self.matcher.orders}
            incidents: list[str] = []
            def reconcile(connection: sqlite3.Connection) -> None:
                records = tuple(connection.execute("SELECT i.intent_id,o.submission,o.dispatch FROM ex_intents i "
                    "JOIN ex_outbox o USING(intent_id) WHERE i.context_id=?", (self.context.identity,)))
                for record in records:
                    identifier = str(record["intent_id"])
                    order = orders.get(identifier)
                    if order is not None:
                        acknowledge_tx(connection, identifier, self._order_id(order.order_id), f"paper-recovery-{identifier}")
                        if order.terminal:
                            terminal_tx(connection, identifier, f"paper-recovery-terminal-{identifier}", complete_fills=True)
                    elif record["submission"] == "PENDING_SUBMISSION":
                        # Matcher state + accounting share one local transaction.
                        # Its complete client-ID inventory is authoritative here.
                        reject_tx(connection, identifier, f"paper-recovery-not-created-{identifier}", proven_no_creation=True)
                    elif record["submission"] == "ACKNOWLEDGED":
                        raise DomainError("PAPER_RECOVERY_LEDGER_CONFLICT")
                self._finalize_episodes_tx(connection, incidents)
            self.writer.call(reconcile)
            self._armed = False
            self._quiesced = True
            self.interlock.reconcile_provisional_unknown(self.context)
            for incident in incidents:
                self.interlock.provisional_fence(self.context.authority_id, incident)

    def _recovery_state_tx(self, connection: sqlite3.Connection) -> tuple[str, bool]:
        row = connection.execute(
            "SELECT context_json,state_json FROM wp_paper_books WHERE authority_id=? "
            "AND environment='SANDBOX' AND scope_id=? AND product_track=?",
            (self.context.authority_id, self.scope, self.context.product_track.value)).fetchone()
        if row is None:
            raise DomainError("PAPER_RECOVERY_STATE_MISSING")
        try:
            current = ContextKey.model_validate_json(row["context_json"])
            if current == self.context:
                if connection.execute("SELECT 1 FROM ex_context_retirements WHERE context_id=?",
                                      (self.context.identity,)).fetchone() is not None:
                    self._verified_retirement_tx(connection, self.context)
                    self._require_flat_matcher(PaperMatcher.restore(
                        self.context, self._instruments, json.loads(row["state_json"])))
                    return str(row["state_json"]), True
                return str(row["state_json"]), False
            archive = connection.execute("SELECT * FROM wp_paper_archives WHERE context_id=?",
                                         (self.context.identity,)).fetchone()
            if (archive is None or archive["scope_id"] != self.scope
                    or ContextKey.model_validate_json(archive["context_json"]) != self.context
                    or ContextKey.model_validate_json(archive["target_context_json"]) != current
                    or sha256(archive["state_json"].encode()).hexdigest() != archive["state_sha256"]):
                raise DomainError("PAPER_RECOVERY_ARCHIVE_UNVERIFIED")
            retirement = self._verified_retirement_tx(connection, self.context)
            if (retirement["last_fact_seq"] != archive["fact_sequence"]
                    or retirement["proof_id"] != archive["retirement_proof_id"]):
                raise DomainError("PAPER_RECOVERY_ARCHIVE_RETIREMENT_MISMATCH")
            authority = connection.execute("SELECT effective_context,effective_config,active_operation "
                "FROM cf_authorities WHERE authority_id=?", (self.context.authority_id,)).fetchone()
            if (authority is None or not authority["active_operation"]
                    or ContextKey.model_validate_json(authority["effective_context"]) != self.context
                    or EngineConfig.model_validate_json(authority["effective_config"]) != self.config):
                raise DomainError("PAPER_RECOVERY_OPERATION_UNVERIFIED")
            pending = connection.execute("SELECT operation_json,stop_proof,retirement "
                "FROM cf_transition_operations WHERE operation_id=? AND authority_id=?",
                (authority["active_operation"], self.context.authority_id)).fetchone()
            if pending is None or not pending["stop_proof"] or not pending["retirement"]:
                raise DomainError("PAPER_RECOVERY_OPERATION_UNVERIFIED")
            operation = TransitionOperation.model_validate_json(pending["operation_json"])
            if (operation.source_context != self.context or operation.target_context != current
                    or operation.proposed_config.execution_scope != (self.scope,)
                    or paper_instruments(operation.proposed_config.product_track,
                                         operation.proposed_config.reporting_currency) != self._default_instruments):
                raise DomainError("PAPER_RECOVERY_OPERATION_MISMATCH")
            RetirementEvidence.model_validate_json(pending["retirement"]).require_retired(self.context)
            proof = StopCertificate.model_validate_json(pending["stop_proof"])
            # Expiry is allowed only for this read-only reconstruction. All
            # original closedness fields must be valid at their issuance; the
            # coordinator obtains fresh evidence before publishing the target.
            proof.require_valid(self.context, (self.scope,), proof.issued_at)
            if proof.fact_sequence != archive["fact_sequence"]:
                raise DomainError("PAPER_RECOVERY_ARCHIVE_RETIREMENT_MISMATCH")
            source = PaperMatcher.restore(self.context, self._instruments, json.loads(archive["state_json"]))
            target = PaperMatcher.restore(current, self._instruments, json.loads(row["state_json"]))
            self._require_flat_matcher(source)
            self._require_flat_matcher(target)
            # A staged target must contain exactly the settled source capital,
            # with no orders ever admitted before effective-context publication.
            if (target.orders or target.fills or target.balances != source.balances
                    or (target.margin is None) != (source.margin is None)
                    or (target.margin is not None and source.margin is not None
                        and target.margin.collateral != source.margin.collateral)
                    or connection.execute("SELECT 1 FROM ex_intents WHERE context_id=? LIMIT 1",
                                          (current.identity,)).fetchone() is not None):
                raise DomainError("PAPER_RECOVERY_STAGED_TARGET_CHANGED")
            provenance = target.dump_state().get("flat_rebind_provenance")
            if (not isinstance(provenance, dict)
                    or provenance.get("source_context") != self.context.model_dump(mode="json")
                    or provenance.get("target_context") != current.model_dump(mode="json")
                    or provenance.get("source_snapshot_sha256") != sha256(json.dumps(
                        source.dump_state(), sort_keys=True, separators=(",", ":")).encode()).hexdigest()):
                raise DomainError("PAPER_RECOVERY_STAGED_PROVENANCE_MISMATCH")
            return str(archive["state_json"]), True
        except (ValueError, TypeError, KeyError):
            raise DomainError("PAPER_RECOVERY_STATE_INVALID") from None

    @staticmethod
    def _verified_retirement_tx(connection: sqlite3.Connection, context: ContextKey) -> sqlite3.Row:
        retirement = connection.execute("SELECT * FROM ex_context_retirements WHERE context_id=?",
                                        (context.identity,)).fetchone()
        if (retirement is None or not retirement["valid"]
                or retirement["authority_id"] != context.authority_id
                or ContextKey.model_validate_json(retirement["context_json"]) != context
                or retirement["last_fact_seq"] != context_fact_sequence_tx(connection, context)):
            raise DomainError("PAPER_SOURCE_RETIREMENT_UNVERIFIED")
        assert_context_closed_tx(connection, context)
        return cast(sqlite3.Row, retirement)

    def _require_flat_matcher(self, matcher: PaperMatcher) -> None:
        if (matcher.open_orders or (matcher.margin is not None and matcher.margin.positions)
                or any(amount != 0 for currency, amount in matcher.balances.items()
                       if currency != self.config.reporting_currency)):
            raise DomainError("PAPER_RECOVERY_ARCHIVE_NOT_FLAT")

    def _persist_tx(self, connection: sqlite3.Connection) -> None:
        if self._retired:
            raise DomainError("PAPER_CONTEXT_RETIRED")
        previous = connection.execute("SELECT context_json,state_json FROM wp_paper_books "
            "WHERE authority_id=? AND environment='SANDBOX' AND scope_id=? AND product_track=?",
            (self.context.authority_id, self.scope, self.context.product_track.value)).fetchone()
        if previous is not None:
            source = ContextKey.model_validate_json(previous["context_json"])
            if source != self.context:
                retirement = self._verified_retirement_tx(connection, source)
                # An immutable source snapshot and the target's book replacement
                # commit together. A crash cannot erase the retired source's
                # evidence while the coordinator still names it as effective.
                connection.execute("INSERT INTO wp_paper_archives VALUES(?,?,?,?,?,?,?,?)",
                    (source.identity, self.scope, source.model_dump_json(), self.context.model_dump_json(),
                     previous["state_json"], sha256(previous["state_json"].encode()).hexdigest(),
                     retirement["last_fact_seq"], retirement["proof_id"]))
        connection.execute(
            "INSERT INTO wp_paper_books VALUES(?,?,?,?,?,?) ON CONFLICT(authority_id,environment,scope_id,product_track) "
            "DO UPDATE SET context_json=excluded.context_json,state_json=excluded.state_json",
            (self.context.authority_id, "SANDBOX", self.scope, self.context.product_track.value,
             self.context.model_dump_json(), json.dumps(self.matcher.dump_state(), sort_keys=True)))

    def _order_id(self, paper_order_id: str) -> str:
        return f"{self.context.identity[:20]}-{paper_order_id}"

    def _finalize_episodes_tx(self, connection: sqlite3.Connection, incidents: list[str]) -> None:
        if self._retired or self.context.product_track != ProductTrack.SPOT:
            return
        result = PaperEpisodeFinalizer.finalize_tx(
            connection, PaperEpisodeFinalizer.capture(self.matcher, self.scope))
        if result.incident_code is not None:
            incidents.append(result.incident_code)

    def create(self, intent: OrderIntent) -> Future[CreateResult]:
        """Called only by Dispatcher under the final-send interlock."""
        output: Future[CreateResult] = Future()
        self.interlock.validate(intent)
        with self._lock:
            if self._retired or intent.context != self.context or intent.scope_id != self.scope:
                raise DomainError("PAPER_CONTEXT_MISMATCH")
            if intent.kind == IntentKind.ENTRY and (not self._armed or self._quiesced):
                raise DomainError("PAPER_ENTRIES_FENCED")
            previous = self.matcher.dump_state()
            try:
                order = self.matcher.submit(PaperOrderRequest(
                    client_order_id=intent.intent_id, instrument_id=intent.instrument,
                    side=PaperSide(intent.side.value), quantity=intent.quantity,
                    limit_price=intent.limit_price, reduce_only=intent.kind != IntentKind.ENTRY),
                    now=datetime.now(timezone.utc))
                order_id = self._order_id(order.order_id)
                def save(connection: sqlite3.Connection) -> None:
                    self._persist_tx(connection)
                    acknowledge_tx(connection, intent.intent_id, order_id, f"paper-accept-{intent.intent_id}")
                self.writer.call(save)
            except BaseException:
                self._matcher = PaperMatcher.restore(self.context, self._instruments, previous)
                raise
            output.set_result(CreateResult(context=self.context, outcome=CreateOutcome.ACCEPTED,
                                            venue_order_id=order_id, evidence_id=f"paper-accept-{intent.intent_id}"))
        self._notify()
        return output

    def update_market(self, instrument: str, *, bids: tuple[DepthLevel, ...],
                      asks: tuple[DepthLevel, ...], now: datetime) -> tuple[PaperFill, ...]:
        """Trusted market ingestion, never a GUI financial command."""
        with self.interlock.lock, self._lock:
            if self._retired:
                raise DomainError("PAPER_CONTEXT_RETIRED")
            previous = self.matcher.dump_state()
            old_depth = dict(self._depth)
            try:
                fills = self.matcher.update_book(instrument, bids=bids, asks=asks, now=now)
                self._depth[instrument] = (bids, asks, now)
                incidents: list[str] = []
                def commit(connection: sqlite3.Connection) -> None:
                    applied: list[tuple[str, Decimal]] = []
                    for item in fills:
                        record = get_tx(connection, item.client_order_id)
                        original = record.intent
                        fill = Fill(context=self.context, scope_id=self.scope, venue_id="coinfly-paper",
                            account_id=self.scope, instrument=item.instrument_id,
                            trade_id=self._order_id(item.trade_id), venue_order_id=self._order_id(item.order_id),
                            evidence_id=self._order_id(item.trade_id), intent_id=item.client_order_id,
                            base_asset=original.base_asset, quote_asset=original.quote_asset,
                            side=Side(item.side.value), quantity=item.quantity, price=item.price,
                            fee=item.fee, fee_asset=item.fee_currency, contract_multiplier=original.contract_multiplier)
                        result = apply_fill_tx(connection, fill)
                        if result.applied:
                            applied.append((result.fill_id, item.fee))
                        if result.incident:
                            incidents.append(result.incident)
                    for order in self.matcher.orders:
                        if order.terminal:
                            terminal_tx(connection, order.client_order_id, f"paper-terminal-{self._order_id(order.order_id)}",
                                        complete_fills=True)
                    self._book_fill_risk_tx(connection, applied)
                    self._persist_tx(connection)
                    self._finalize_episodes_tx(connection, incidents)
                self.writer.call(commit)
                for incident in incidents:
                    self.interlock.provisional_fence(self.context.authority_id, incident)
            except BaseException:
                self._matcher = PaperMatcher.restore(self.context, self._instruments, previous)
                self._depth = old_depth
                self.interlock.provisional_fence(self.context.authority_id, "PAPER_ACCOUNTING_FAILURE")
                raise
            self._depth[instrument] = (bids, asks, now)
        self._notify()
        return fills

    @exact_decimal
    def _book_fill_risk_tx(self, connection: sqlite3.Connection, applied: list[tuple[str, Decimal]]) -> None:
        if not applied:
            return
        pnl = Decimal(0)
        for identifier, fee in applied:
            row = connection.execute("SELECT realized_pnl FROM ex_lot_movements WHERE fill_id=?", (identifier,)).fetchone()
            if row is not None:
                pnl += Decimal(row[0])
            pnl -= fee
        previous = self.admission.drawdown.read_tx(connection, self.context, self.scope, self.config.reporting_currency)
        if previous is None:
            fence_authority_tx(connection, self.context, "LOSS_HISTORY_UNVERIFIED", applied[-1][0])
            return
        equity = self.matcher.balances.get(self.config.reporting_currency, Decimal(0))
        missing = False
        if self.matcher.margin is not None:
            margin = self.matcher.margin.snapshot()
            if margin.equity is None:
                missing = True
            else:
                equity = margin.equity
        for contract in self._instruments if self.matcher.margin is None else ():
            amount = self.matcher.balances.get(contract.base_currency, Decimal(0))
            if not amount:
                continue
            depth = self._depth.get(contract.instrument_id)
            if depth is None or not depth[0] or not depth[1]:
                missing = True
                break
            equity += amount * (depth[0][0].price + depth[1][0].price) / 2
        if missing:
            # Keep booked daily P&L even when mark-based NAV cannot be refreshed.
            # Missing valuation independently fences further admission.
            equity = previous.units * previous.unit_nav
            fence_authority_tx(connection, self.context, "POSITION_MARK_UNVERIFIED", applied[-1][0])
        self.admission.drawdown.record_tx(connection, self.context, self.scope,
            equity=equity, realized_pnl=pnl, evidence_id=f"paper-fill-risk-{applied[-1][0]}",
            observed_at=datetime.now(timezone.utc), currency=self.config.reporting_currency)

    def arm(self) -> None:
        self._ready()
        with self._lock:
            if self._retired:
                raise DomainError("PAPER_CONTEXT_RETIRED")
            if (self.context.product_track == ProductTrack.PERPETUAL) != (self.matcher.margin is not None):
                raise DomainError("PERPETUAL_MARGIN_UNCERTIFIED")
            self._armed = True
            self._quiesced = False

    def quiesce(self) -> None:
        with self._lock:
            self._quiesced = True
            self._armed = False
            self._enabled_slots.clear()

    def _record_decision_cause(self, intent_id: str, kind: IntentKind, cause: dict[str, Any]) -> None:
        def save(connection: sqlite3.Connection) -> None:
            record_cause_tx(connection, intent_id=intent_id, context_id=self.context.identity,
                            cause="DECODED_DECISION_EXIT" if kind is IntentKind.EXIT else "DECODED_DECISION_ENTRY",
                            origin="AUTOMATION", decision_id=str(cause["decision_id"]), controller_profile=cause.get("controller_profile"),
                            pipeline_fixture=bool(cause.get("pipeline_fixture", False)))
        self.writer.call(save)

    # --- synthetic settlement schedule (paper derivatives only) ------------------------
    def settle(self, now: datetime) -> tuple[dict[str, Any], ...]:
        """Apply the declared SYNTHETIC funding / settlement events that are due by ``now``.

        The paper perpetual book applies funding on a fixed schedule per declared
        subtype (``PERPETUAL_NO_EXPIRY``: every 8 h at 00/08/16 UTC;
        ``PERPETUAL_STYLE_FUTURE``: hourly) at the declared synthetic rate
        (``PAPER_FUNDING_RATE_PER_INTERVAL``, long pays when positive) against the
        last mark, once per interval (idempotent by event id), journaled as
        ``PAPER_FUNDING``. A ``DATED_FUTURE`` position is cash-settled at its
        catalog expiry (``PAPER_EXPIRY_SETTLEMENT``): the position is closed at
        the mark. Every event is labeled synthetic; none is venue evidence.
        """
        with self.interlock.lock, self._lock:
            if self._retired or self.matcher.margin is None:
                return ()
            margin = self.matcher.margin
            events: list[dict[str, Any]] = []
            previous = self._settlement_cursor
            self._settlement_cursor = now
            if previous is None or now <= previous:
                return ()  # no retroactive funding: boundaries are charged when the clock crosses them
            for position in margin.positions:
                instrument = position.instrument_id
                contract = next((item for item in self._instruments if item.instrument_id == instrument), None)
                depth = self._depth.get(instrument)
                if contract is None or depth is None or not depth[0] or not depth[1]:
                    continue
                mark = (depth[0][0].price + depth[1][0].price) / 2
                subtype = contract.declared_subtype
                interval = PAPER_FUNDING_INTERVALS.get(subtype)
                if interval is not None:
                    boundary = _interval_start(now, interval)
                    while boundary > previous:
                        stamp = boundary.strftime("%Y%m%dT%H%M%SZ")
                        event_id = f"paper-funding:{instrument}:{stamp}"
                        if event_id not in self._settled_events:
                            payment = -(PAPER_FUNDING_RATE_PER_INTERVAL * position.quantity * mark * contract.contract_multiplier)
                            applied = margin.apply_funding(event_id, instrument, payment)
                            self._settled_events.add(event_id)
                            if applied:
                                events.append({"kind": "PAPER_FUNDING", "event_id": event_id, "instrument": instrument, "payment": str(payment),
                                               "rate": str(PAPER_FUNDING_RATE_PER_INTERVAL), "synthetic": True,
                                               "interval_start": boundary.isoformat()})
                        boundary -= interval
                expiry = getattr(contract, "expiry", None)
                if subtype is ProductSubtype.DATED_FUTURE and expiry is not None and now >= expiry:
                    event_id = f"paper-expiry:{instrument}:{expiry.strftime('%Y%m%dT%H%M%SZ')}"
                    if event_id not in self._settled_events:
                        realized = margin.apply_fill(instrument, -position.quantity, mark, multiplier=contract.contract_multiplier,
                                                     fee=Decimal(0), reduce_only=True)
                        self._settled_events.add(event_id)
                        events.append({"kind": "PAPER_EXPIRY_SETTLEMENT", "event_id": event_id, "instrument": instrument,
                                       "quantity": str(position.quantity), "mark": str(mark), "realized": str(realized), "synthetic": True})
            if events:
                def save(connection: sqlite3.Connection) -> None:
                    for event in events:
                        amount = Decimal(event.get("payment") or event.get("realized") or "0")
                        if amount != 0:
                            post_tx(connection, JournalFrame(context=self.context, scope_id=self.scope, event_kind=event["kind"],
                                    evidence_id=event["event_id"],
                                    entries=(JournalEntry(account="assets:collateral", asset=self.config.reporting_currency, amount=amount),
                                             JournalEntry(account="pnl:synthetic_settlement", asset=self.config.reporting_currency, amount=-amount))))
                    self._persist_tx(connection)
                self.writer.call(save)
                self._notify()
            return tuple(events)

    def instrument_contract(self, instrument_id: str) -> PaperInstrument:
        for item in self._instruments:
            if item.instrument_id == instrument_id:
                return item
        raise DomainError("PAPER_INSTRUMENT_UNKNOWN")

    def cancel_intent(self, intent_id: str) -> dict[str, Any]:
        """Cancel one resting paper order (order TTL policy); reports what the book showed.

        The result names the filled quantity and whether the current book crossed
        the limit when cancelled, so the caller can distinguish a nonmarketable
        limit from missing liquidity. Nothing is converted to a market order.
        """
        with self.interlock.lock, self._lock:
            if self._retired:
                raise DomainError("PAPER_CONTEXT_RETIRED")
            order = next((item for item in self.matcher.open_orders if item.client_order_id == intent_id), None)
            if order is None:
                return {"cancelled": False, "reason": "ORDER_NOT_OPEN"}
            depth = self._depth.get(order.instrument_id)
            crossed = False
            if depth is not None and depth[0] and depth[1]:
                bids, asks, _ = depth
                crossed = (asks[0].price <= order.request.limit_price) if order.side == PaperSide.BUY else (bids[0].price >= order.request.limit_price)
            filled = order.filled_quantity
            self._cancel_orders([order.order_id])
            return {"cancelled": True, "filled_quantity": str(filled), "remaining_quantity": str(order.quantity - filled),
                    "limit_crossed_at_cancel": crossed, "instrument": order.instrument_id}

    def _cancel(self, slot: SlotRecord | None = None) -> None:
        with self.interlock.lock, self._lock:
            if self._retired:
                raise DomainError("PAPER_CONTEXT_RETIRED")
            self._cancel_orders([order.order_id for order in self.matcher.open_orders
                                 if slot is None or order.instrument_id == slot.instrument])

    def _cancel_orders(self, order_ids: list[str]) -> None:
        with self.interlock.lock, self._lock:
            previous = self.matcher.dump_state()
            cancelled: list[str] = []
            for order_id in order_ids:
                order = self.matcher.order(order_id)
                if order.terminal:
                    continue
                self.matcher.cancel(order.order_id, now=datetime.now(timezone.utc))
                cancelled.append(order.client_order_id)
            try:
                incidents: list[str] = []
                def save(connection: sqlite3.Connection) -> None:
                    for intent_id in cancelled:
                        terminal_tx(connection, intent_id, f"paper-cancel-{intent_id}", complete_fills=True)
                    self._persist_tx(connection)
                    self._finalize_episodes_tx(connection, incidents)
                self.writer.call(save)
                for incident in incidents:
                    self.interlock.provisional_fence(self.context.authority_id, incident)
            except BaseException:
                self._matcher = PaperMatcher.restore(self.context, self._instruments, previous)
                raise

    def drain(self, policy: DrainPolicy) -> None:
        # Context and slot control actors can request drains concurrently. One
        # planner per engine avoids cancelling each other's protective orders.
        with self._drain_lock:
            self._cancel()
            self._close_residuals(policy)
            self.writer.call(lambda connection: assert_context_closed_tx(connection, self.context))

    @exact_decimal
    def _close_residuals(self, policy: DrainPolicy, slot: SlotRecord | None = None) -> None:
        """Only a current, admitted protective order may close a residual position."""
        deadline = datetime.now(timezone.utc) + timedelta(seconds=policy.timeout_seconds)
        for _ in range(1000):
            now = datetime.now(timezone.utc)
            if now >= deadline:
                raise DomainError("DRAIN_DEADLINE_EXCEEDED")
            rows = self.writer.call(lambda connection: [dict(row) for row in connection.execute(
                "SELECT instrument,quantity FROM ex_positions WHERE context_id=?", (self.context.identity,))])
            residual = next((row for row in rows if Decimal(row["quantity"]) != 0
                             and (slot is None or row["instrument"] == slot.instrument)), None)
            if residual is None:
                return
            instrument = str(residual["instrument"])
            contract = next(item for item in self._instruments if item.instrument_id == instrument)
            with self._lock:
                depth = self._depth.get(instrument)
                if depth is None or now - depth[2] > timedelta(seconds=5) or now < depth[2]:
                    raise DomainError("DRAIN_FRESH_MARKET_REQUIRED")
                bids, asks, stamp = depth
                holding = Decimal(residual["quantity"])
                if holding == 0 or not bids or not asks:
                    raise DomainError("DRAIN_REDUCING_SIDE_UNPROVEN")
                if holding < 0 and self.context.product_track == ProductTrack.SPOT:
                    raise DomainError("DRAIN_REDUCING_SIDE_UNPROVEN")
                if holding > 0:
                    # Long residual: sell into the bids, never below the slippage floor.
                    side = Side.SELL
                    price = (bids[0].price * (1 - policy.max_slippage_fraction) / contract.price_increment
                             ).to_integral_value(rounding=ROUND_UP) * contract.price_increment
                    budget = sum((level.quantity for level in bids if level.price >= price), Decimal(0))
                else:
                    # Short residual (paper derivatives): buy back from the asks.
                    side = Side.BUY
                    price = (asks[0].price * (1 + policy.max_slippage_fraction) / contract.price_increment
                             ).to_integral_value(rounding=ROUND_DOWN) * contract.price_increment
                    budget = sum((level.quantity for level in asks if level.price <= price), Decimal(0))
                used_stamp, used = self._drain_used.get(instrument, (stamp, Decimal(0)))
                budget = budget * policy.max_participation_fraction - (used if used_stamp == stamp else Decimal(0))
                quantity = min(abs(holding), budget, self.config.limits.max_order_notional / (price * contract.contract_multiplier))
                quantity = (quantity / contract.quantity_increment).to_integral_value(rounding=ROUND_DOWN) * contract.quantity_increment
                if quantity <= 0 or quantity * price < contract.minimum_notional:
                    raise DomainError("DRAIN_DUST_OR_LIQUIDITY_BLOCKED")
            owning_slot = slot or self._slot_for(instrument)
            book = self.observe_execution_book()
            intent = OrderIntent(context=self.context, scope_id=self.scope, profile_version=1, signer_version=0,
                slot_id=owning_slot.slot_id, allocation_revision=book.fact_sequence, instrument=instrument,
                base_asset=contract.base_currency, quote_asset=contract.quote_currency,
                side=side, kind=IntentKind.EXIT, quantity=quantity, limit_price=price,
                contract_multiplier=contract.contract_multiplier, child_index=self._next_exit_child())
            record = self.admission.admit(intent)
            # A protective drain is never a strategy trade: label it before it dispatches.
            self.writer.call(lambda connection: record_cause_tx(
                connection, intent_id=record.intent.intent_id, context_id=self.context.identity, cause="PROTECTIVE_DRAIN",
                origin="SLOT_DRAIN" if slot is not None else "CONTEXT_DRAIN"))
            Dispatcher(self.writer, self.interlock, self, reducer=self.reducer).dispatch(record.intent.intent_id).result(timeout=5)
            with self._lock:
                self._drain_used[instrument] = (stamp, (used if used_stamp == stamp else Decimal(0)) + quantity)
            self._advance_pending()
            remaining = self.writer.call(lambda connection: get_tx(connection, record.intent.intent_id))
            if not remaining.terminal:
                raise DomainError("DRAIN_AWAITING_LIQUIDITY")
        raise DomainError("DRAIN_OPERATION_BUDGET_EXCEEDED")

    def _next_exit_child(self) -> int:
        return self.writer.call(lambda connection: int(connection.execute(
            "SELECT COUNT(*) FROM ex_intents WHERE context_id=?", (self.context.identity,)).fetchone()[0]))

    def _slot_for(self, instrument: str) -> SlotRecord:
        from coinfly.control.slot_service import SlotService

        row = self.writer.call(lambda connection: connection.execute(
            "SELECT * FROM cf_slots WHERE context_id=? AND instrument=? AND tombstoned=0",
            (self.context.identity, instrument)).fetchone())
        if row is None:
            raise DomainError("POSITION_SLOT_UNATTRIBUTED")
        return SlotService._record(row)

    @exact_decimal
    def observe_execution_book(self) -> ActiveBookSnapshot:
        """Derive admission authority solely from this synthetic execution book."""
        now = datetime.now(timezone.utc)
        with self._lock:
            # Each mark carries its instrument's contract size: the weight
            # planner sizes contracts as weight x equity / (price x multiplier),
            # and a multiplier of 1 on a 0.01-BTC contract would plan 100x the
            # intended notional (and bind intents to the wrong contract size).
            multipliers = {item.instrument_id: item.contract_multiplier for item in self._instruments}
            marks = tuple(ExecutionMark(instrument=instrument, price=(bids[0].price + asks[0].price) / 2,
                                        contract_multiplier=multipliers.get(instrument, Decimal(1)))
                          for instrument, (bids, asks, stamp) in self._depth.items()
                          if bids and asks and timedelta(0) <= now - stamp <= timedelta(seconds=5))
            mark_map = {item.instrument: item.price for item in marks}
            balances = self.matcher.balances
            margin = self.matcher.margin
            if margin is not None:
                # Paper perpetual book: equity = settled collateral + unrealized P&L at
                # fresh marks; the margin available for new risk is the eligible
                # collateral net of initial margin already in use.
                for position in margin.positions:
                    if position.instrument_id not in mark_map:
                        raise DomainError("POSITION_MARK_UNVERIFIED")
                    margin.set_mark(position.instrument_id, mark_map[position.instrument_id])
                snapshot = margin.snapshot()
                if snapshot.equity is None or snapshot.available_margin is None:
                    raise DomainError("POSITION_MARK_UNVERIFIED")
                equity = snapshot.equity
                eligible = snapshot.equity
                available: tuple[AvailableAsset, ...] = (AvailableAsset(asset=self.config.reporting_currency,
                                                                          amount=max(Decimal(0), snapshot.available_margin)),)
            else:
                equity = balances.get(self.config.reporting_currency, Decimal(0))
                for contract in self._instruments:
                    amount = balances.get(contract.base_currency, Decimal(0))
                    if amount and contract.instrument_id not in mark_map:
                        raise DomainError("POSITION_MARK_UNVERIFIED")
                    equity += amount * mark_map.get(contract.instrument_id, Decimal(0))
                eligible = balances.get(self.config.reporting_currency, Decimal(0))
                available = tuple(AvailableAsset(asset=key, amount=value) for key, value in self.matcher.available_balances.items())
            sequence = self.writer.call(lambda connection: context_fact_sequence_tx(connection, self.context))
            book = ActiveBookSnapshot(context=self.context, scope_id=self.scope, evidence_id=str(uuid4()),
                observed_at=now, expires_at=now + timedelta(seconds=5), fact_sequence=sequence,
                reporting_currency=self.config.reporting_currency, funded_equity=equity,
                eligible_collateral=eligible,
                available_assets=available,
                marks=marks, reservations_in_remote_holds=tuple(order.client_order_id for order in self.matcher.open_orders),
                complete_execution_scope=True, authoritative_account_evidence=True, conflicting_external_activity=False)
        self.admission.drawdown.record(self.context, self.scope, equity=equity, evidence_id=book.evidence_id,
                                       observed_at=now, currency=self.config.reporting_currency)
        self.admission.observe(book)
        return book

    @exact_decimal
    def submit_target(self, target: BoundTarget, *, constraint: Callable[[PlannedDelta, ActiveBookSnapshot], PlannedDelta] | None = None,
                      cause: dict[str, Any] | None = None) -> tuple[str, ...]:
        """Trusted weight boundary; no GUI/model-supplied balance or route is read.

        ``constraint`` (the strategy's declared execution policy, e.g. the exact
        turnover guard) may reduce a planned quantity or raise a DomainError; it
        can never substitute another instrument, side or trade. ``cause`` names
        the decoded decision every resulting intent traces to (``decision_id``,
        ``controller_profile``, ``pipeline_fixture``); it is recorded before dispatch.
        """
        if target.context != self.context or not self._armed or self._quiesced:
            raise DomainError("STALE_OR_UNARMED_TARGET")
        book = self.observe_execution_book()
        actual = self.writer.call(lambda connection: {str(row[0]): Decimal(row[1]) for row in connection.execute(
            "SELECT instrument,quantity FROM ex_positions WHERE context_id=?", (self.context.identity,))})
        def pending(connection: sqlite3.Connection) -> dict[str, Decimal]:
            result: dict[str, Decimal] = {}
            for row in connection.execute("SELECT i.payload_json,o.filled_quantity FROM ex_intents i JOIN ex_outbox o USING(intent_id) "
                                          "WHERE i.context_id=? AND o.terminal=0", (self.context.identity,)):
                intent = OrderIntent.model_validate_json(row[0])
                quantity = (intent.quantity - Decimal(row[1])) * (1 if intent.side == Side.BUY else -1)
                result[intent.instrument] = result.get(intent.instrument, Decimal(0)) + quantity
            return result
        contracts = tuple(InstrumentContract(instrument=item.instrument_id, quantity_increment=item.quantity_increment,
                          price_increment=item.price_increment, minimum_quantity=item.quantity_increment,
                          minimum_notional=item.minimum_notional) for item in self._instruments)
        from coinfly.strategy.capital import planning_book_tx

        planning_book, owned_actual = self.writer.call(
            lambda connection: planning_book_tx(connection, book, target.strategy_identity))
        if owned_actual is not None:
            actual = owned_actual
        planned = plan_weights(target=target, book=planning_book, contracts=contracts, actual_quantities=actual,
                               pending_signed_quantities=self.writer.call(pending), now=datetime.now(timezone.utc))
        ids = []
        for child, delta in enumerate(planned):
            if datetime.now(timezone.utc) >= target.proposal.expires_at:
                raise DomainError("TARGET_EXPIRED")
            current_book = self.observe_execution_book()
            if constraint is not None:
                allocated_book, _ = self.writer.call(
                    lambda connection: planning_book_tx(connection, current_book, target.strategy_identity))
                constrained = constraint(delta, allocated_book)
                if (constrained.instrument != delta.instrument or constrained.side != delta.side or constrained.kind != delta.kind
                        or constrained.quantity > delta.quantity or constrained.quantity <= 0):
                    raise DomainError("EXECUTION_CONSTRAINT_INVALID")
                delta = constrained
            contract = next(item for item in self._instruments if item.instrument_id == delta.instrument)
            slot = self._slot_for(delta.instrument)
            intent = OrderIntent(context=self.context, scope_id=self.scope, profile_version=1, signer_version=0,
                slot_id=slot.slot_id, allocation_revision=target.proposal.allocation_revision,
                instrument=delta.instrument, base_asset=contract.base_currency, quote_asset=contract.quote_currency,
                side=delta.side, kind=delta.kind, quantity=delta.quantity, limit_price=delta.limit_price,
                contract_multiplier=delta.contract_multiplier, child_index=child)
            record = self.admission.admit(intent)
            if cause is not None:
                self._record_decision_cause(record.intent.intent_id, delta.kind, cause)
            Dispatcher(self.writer, self.interlock, self, reducer=self.reducer).dispatch(record.intent.intent_id).result(timeout=5)
            ids.append(record.intent.intent_id)
        self._advance_pending()
        return tuple(ids)

    def _advance_pending(self) -> None:
        with self.interlock.lock, self._lock:
            before = self.matcher.dump_state()
            fills = self.matcher.advance(now=datetime.now(timezone.utc))
            try:
                incidents: list[str] = []
                def commit(connection: sqlite3.Connection) -> None:
                    applied: list[tuple[str, Decimal]] = []
                    for item in fills:
                        original = get_tx(connection, item.client_order_id).intent
                        result = apply_fill_tx(connection, Fill(context=self.context, scope_id=self.scope,
                            venue_id="coinfly-paper", account_id=self.scope, instrument=item.instrument_id,
                            trade_id=self._order_id(item.trade_id), venue_order_id=self._order_id(item.order_id),
                            evidence_id=self._order_id(item.trade_id), intent_id=item.client_order_id,
                            base_asset=original.base_asset, quote_asset=original.quote_asset, side=Side(item.side.value),
                            quantity=item.quantity, price=item.price, fee=item.fee, fee_asset=item.fee_currency,
                            contract_multiplier=original.contract_multiplier))
                        if result.applied:
                            applied.append((result.fill_id, item.fee))
                        if result.incident:
                            raise DomainError(result.incident)
                    for order in self.matcher.orders:
                        if order.terminal:
                            terminal_tx(connection, order.client_order_id,
                                        f"paper-terminal-{self._order_id(order.order_id)}", complete_fills=True)
                    self._book_fill_risk_tx(connection, applied)
                    self._persist_tx(connection)
                    self._finalize_episodes_tx(connection, incidents)
                self.writer.call(commit)
                for incident in incidents:
                    self.interlock.provisional_fence(self.context.authority_id, incident)
            except BaseException:
                self._matcher = PaperMatcher.restore(self.context, self._instruments, before)
                self.interlock.provisional_fence(self.context.authority_id, "PAPER_ACCOUNTING_FAILURE")
                raise
        self._notify()

    def _certificate(self, slot: SlotRecord | None = None) -> StopCertificate:
        now = datetime.now(timezone.utc)
        with self._lock:
            orders = tuple(order for order in self.matcher.open_orders
                           if slot is None or order.instrument_id == slot.instrument)
            if orders:
                raise DomainError("STOP_PROOF_OUTSTANDING_VENUE_ORDER")
            if slot is None:
                if self.matcher.margin is not None and self.matcher.margin.positions:
                    raise DomainError("STOP_PROOF_POSITION_NONZERO")
                if any(amount != 0 for currency, amount in self.matcher.balances.items()
                       if currency != self.config.reporting_currency):
                    raise DomainError("STOP_PROOF_POSITION_NONZERO")
            def evidence(connection: sqlite3.Connection) -> int:
                if slot is None:
                    assert_context_closed_tx(connection, self.context)
                    return context_fact_sequence_tx(connection, self.context)
                assert_slot_closed_tx(connection, self.context, slot.slot_id)
                return slot_fact_sequence_tx(connection, self.context, slot.slot_id)
            sequence = self.writer.call(evidence)
            return StopCertificate(proof_id=str(uuid4()), context=self.context, execution_scope=(self.scope,),
                issued_at=now, expires_at=now + timedelta(seconds=30), fact_sequence=sequence,
                watermarks=(ScopeWatermark(scope_id=self.scope, evidence_id=f"paper-state-{sequence}",
                    account_observed_at=now, account_stream_sequence=sequence, applied_stream_sequence=sequence,
                    history_complete=True, account_complete=True),),
                residual_positions=(), outstanding_order_ids=(), unresolved_create_ids=(), unapplied_fill_count=0,
                all_delegated_positions_covered=True, all_related_orders_terminal=True,
                dispatch_tasks_fenced=self._quiesced or slot is not None and slot.slot_id not in self._enabled_slots,
                task_fence_evidence_id=f"paper-fenced-{self.context.epoch}")

    def reconcile(self) -> StopCertificate:
        return self._certificate()

    def retire(self) -> RetirementEvidence:
        with self._lock:
            self._quiesced = True
            self._armed = False
            self._retired = True
            self._enabled_slots.clear()
            return RetirementEvidence(context=self.context, evidence_id=str(uuid4()),
                mutation_transports_retired=True, signing_handles_retired=True,
                all_tasks_joined_or_fenced=True, grants_revoked=True)

    def reset_transient(self) -> None:
        with self._lock:
            if not self._retired:
                raise DomainError("RESET_REQUIRES_RETIREMENT")
            self._depth.clear()
            self._drain_used.clear()
            self._enabled_slots.clear()

    def start_slot(self, slot: SlotRecord) -> None:
        self._ready()
        if slot.context != self.context or slot.instrument not in {item.instrument_id for item in self._instruments}:
            raise DomainError("PAPER_INSTRUMENT_UNAVAILABLE")
        with self._lock:
            if not self._armed or self._retired or self._quiesced:
                raise DomainError("PAPER_ENTRIES_FENCED")
            self._enabled_slots.add(slot.slot_id)

    def quiesce_slot(self, slot: SlotRecord) -> None:
        with self._lock:
            self._enabled_slots.discard(slot.slot_id)

    def drain_slot(self, slot: SlotRecord, policy: DrainPolicy) -> None:
        with self._drain_lock:
            self._cancel(slot)
            self._close_residuals(policy, slot)

    def reconcile_slot(self, slot: SlotRecord) -> SlotStopProof:
        return SlotStopProof(slot_id=slot.slot_id, certificate=self._certificate(slot))

    @exact_decimal
    def balance_snapshot(self) -> dict[str, Any]:
        with self._lock:
            matcher = self.matcher
            cash = matcher.balances.get(self.config.reporting_currency, Decimal(0))
            available = matcher.available_balances.get(self.config.reporting_currency, Decimal(0))
            missing_mark = any(value != 0 for key, value in matcher.balances.items()
                               if key != self.config.reporting_currency)
            unsettled: Decimal | None = Decimal(0)
            if matcher.margin is not None:
                margin = matcher.margin.snapshot()
                cash = margin.collateral
                available = margin.available_margin if margin.available_margin is not None else Decimal(0)
                unsettled = margin.unrealized_pnl
                missing_mark = margin.equity is None
            total = None if missing_mark else cash + (unsettled or Decimal(0))
            return {"environment": "SANDBOX", "simulated": True,
                    "reporting_currency": self.config.reporting_currency,
                    "coverage": "PARTIAL" if missing_mark else "COMPLETE_VERIFIED",
                    "total": str(total) if total is not None else None, "settled_assets": str(cash),
                    "active_book_available": str(available) if not missing_mark else None,
                    "unsettled_perpetual_upl": str(unsettled) if unsettled is not None else None,
                    "included_scopes": 1, "expected_scopes": 1,
                    "label": "SIMULATED — LOCAL PAPER BOOK", "observation_age_seconds": 0,
                    "valuation_provenance": "LOCAL_PAPER_LEDGER",
                    "funding": {"amount": str(self.config.paper_funding.amount),
                                "currency": self.config.paper_funding.currency,
                                "seeded": True},
                    # What the paper venue does and does not model, stated once.
                    "fill_model": {"kind": "LIMIT_CROSSES_DISPLAYED_DEPTH", "partial_fills": True, "liquidity_consumed_per_snapshot": True,
                                   "queue_position": "NOT_MODELED", "latency_microseconds": int(matcher.latency.total_seconds() * 1_000_000)
                                   if hasattr(matcher, "latency") else 0,
                                   "synthetic_funding_rate_per_interval": str(PAPER_FUNDING_RATE_PER_INTERVAL),
                                   "funding_intervals": {key.value: int(value.total_seconds()) for key, value in PAPER_FUNDING_INTERVALS.items()},
                                   "expiry_settlement": "CASH_AT_MARK"}}

    def _notify(self) -> None:
        if self._on_change is not None:
            try:
                self._on_change()
            except Exception:
                # Observer failure cannot undo a committed acceptance or fill.
                # The IPC adapter must resnapshot clients after publication gaps.
                pass
